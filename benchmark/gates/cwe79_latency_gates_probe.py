"""CWE-79 latency-lever lock: the two productive-type gates and the CWE-79 prune index.

Why this gate exists
--------------------
Three engine edits carry the whole latency case for the two CWE-79 collectors, and until this file none
of them had a lock:

  L1a  `_collect_template_response_xss_findings` skips every node that is not `Assign` or `Call`
       before it climbs scopes (`ast_scanner.py:25064`);
  L1a' `_collect_cwe79_xss_recovery_findings` skips every node outside nine types before the same
       climb (`ast_scanner.py:21853`);
  L2   the phase-10.3 prune indexes `sink_records` once by `id(security_node)` and re-checks with `is`
       (`ast_scanner.py:21536`), instead of rescanning the whole list per sink -- the quadratic scan.

They are pure-perf edits: each is a `continue` in front of two pure reads, or a faster route to the same
record. So the contract is two-sided and both sides are machine-checked here.

  (a) the lever may never move a finding -- proved as equivalence, arm over arm, on every shape; and
  (b) the lever must never be widened past what the rules below it actually read -- proved by
      GATE == UNION, where the union is recomputed from the AST of the loop body on every run. That is
      the false-negative direction: a gate that drops a type a rule reads deletes that rule's findings
      silently, and a row count is exactly the instrument that cannot see it.

Measured on the shipped engine (this run, and re-runnable with `--mutate=`)
--------------------------------------------------------------------------
  gate == union of rule head tests  recovery True (9 types), template True (2 types)
  gate placed before _scope_for      recovery True (gate 21853 < read 21857), template True (25064 < 25066)
  shapes owned by a gated type       15, one per gated type per collector, every one loud on the
                                     shipped engine, and the identical row set arm over arm
  index law                          1 build pass, id-keyed, `is` re-checked, function-local
  blessed CWE-79 population          15 parity keys, 0 big8 keys (counted from the frozen baselines)
  what the levers buy (paired, order-alternating, the engine's own perf_counter per collector,
  3 Big-8 modules = 928,617 bytes, 3 reps x 3 pairs, medians) :
      shipped 227.69 ms vs recovery gate removed 447.80 ms  -> CPU ratio 0.5085 (the gate halves
      the two collectors' own time); both levers off 476.91 ms -> 0.4774.
      shipped 232.14 ms vs the quadratic prune scan 230.01 ms -> 1.0092, inside the 189-248 ms leg
      spread: the index retires 168 x 169 = 28,392 inner iterations per scan down to 337 dict
      operations, which is the right law but not a measurable win on this corpus. Reported as
      measured, not as a speed-up. Parent peak RSS 96.6 / 159.8 MB.

Falsifications -- two routes, because the harness must not write an engine
---------------------------------------------------------------------------
`--mutate=NAME` patches the engine **text** in memory and runs TIER 1/TIER 2 against it, so every
lever has a string-tier that fails when the lever is weakened. The behavioural half runs the clean
probe with `TCS_C79_LAT_ENGINE` pointing at a patched copy generated by `scratch/_lat_engines.py`
(git-ignored): a tracked harness that wrote a `.py` and imported it *is* the CWE-94 shape this
product reports, and parity scans `benchmark/`, so that route is fixed, never excused.

  --mutate=recovery_gate_drops_dict             AST.Dict leaves the tuple -> T1 fails on 3 labels
      ...and under the seam 2 shapes go silent: TEMPLATE_AUTOESCAPE_DISABLED, LAMBDA_HTML_BODY_RESPONSE
  --mutate=template_gate_drops_assign           the Assign rule is skipped -> T1 fails on 3 labels
      ...and under the seam HTTP_RESPONSE_HTML goes silent on `response_body_assign`
  --mutate=recovery_gate_removed                pure-perf removal -> T1 fails on 5 labels, rows
      identical in both routes: an unguarded loop is a loop nobody proved
  --mutate=recovery_gate_moved_after_scope_read the gate sits after the climb -> 1 label, rows identical
  --mutate=index_replaced_by_linear_scan        HEAD's quadratic scan back -> T2 fails on 5 labels
  --mutate=index_stored_on_instance_state       a tracker-held memo dict -> T2 fails (RAM mandate)

Exit 1 on any mismatch, 0 only when every lever still matches its proof.
"""
